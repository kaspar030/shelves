#!/usr/bin/env python3
"""Cluster-shelf pipeline: manifest -> generated µcad -> exported STL.

Reads shelves.toml, generates one .µcad source per entry into gen/, then
invokes `microcad export` for each, writing STLs into build/.

Usage:
    scripts/build.py                # generate + export everything
    scripts/build.py --gen-only     # only (re)generate gen/*.µcad
    scripts/build.py rpi4_tray ...  # build only the named shelves
"""
from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GEN = ROOT / "gen"
BUILD = ROOT / "build"
CONFIG = ROOT / ".microcad.toml"
MANIFEST = ROOT / "shelves.toml"

VALID_DEVICES = {"rpi4", "rpi_zero", "pico", "minipc"}
VALID_KINDS = {"tray": "Tray", "drawer": "Drawer"}


def render(shelf: dict) -> str:
    """Render one manifest entry to µcad source."""
    device = shelf["device"]
    kind = shelf["kind"]
    name = shelf["name"]
    if device not in VALID_DEVICES:
        raise ValueError(f"{name}: unknown device {device!r}")
    if kind not in VALID_KINDS:
        raise ValueError(f"{name}: unknown kind {kind!r}")

    workbench = VALID_KINDS[kind]
    height = shelf.get("height", "dev::TRAY_H")
    vents = str(shelf.get("vents", True)).lower()
    width = shelf.get("width", "dev::FOOTPRINT_W")
    depth = shelf.get("depth", "dev::FOOTPRINT_D")

    args = [
        f"width = {width}",
        f"depth = {depth}",
        f"height = {height}",
        "hole_dx = dev::HOLE_DX",
        "hole_dy = dev::HOLE_DY",
        "post_d = dev::POST_D",
        "screw_d = dev::SCREW_D",
        "standoff_h = dev::STANDOFF_H",
        f"vents = {vents}",
    ]
    arg_block = ",\n    ".join(args)

    return f"""// GENERATED by scripts/build.py from shelves.toml — do not edit by hand.
// shelf: {name}  (device={device}, kind={kind})
use lib::tray::*;
use lib::devices::{device} as dev;

#[export("build/{name}.stl")]
{workbench}(
    {arg_block},
);
"""


def load_manifest() -> list[dict]:
    with MANIFEST.open("rb") as f:
        data = tomllib.load(f)
    shelves = data.get("shelf", [])
    if not shelves:
        sys.exit("shelves.toml contains no [[shelf]] entries")
    return shelves


def microcad() -> str:
    exe = shutil.which("microcad")
    if not exe:
        sys.exit("`microcad` not found on PATH. Install with: cargo install microcad")
    return exe


def main() -> int:
    ap = argparse.ArgumentParser(description="Build cluster shelves with microcad.")
    ap.add_argument("names", nargs="*", help="Only build these shelf names.")
    ap.add_argument("--gen-only", action="store_true", help="Generate sources, do not export.")
    ap.add_argument("--resolution", default=None, help="Export resolution, e.g. 0.05mm or 200%%.")
    args = ap.parse_args()

    GEN.mkdir(exist_ok=True)
    BUILD.mkdir(exist_ok=True)

    shelves = load_manifest()
    if args.names:
        wanted = set(args.names)
        shelves = [s for s in shelves if s["name"] in wanted]
        missing = wanted - {s["name"] for s in shelves}
        if missing:
            sys.exit(f"unknown shelf name(s): {', '.join(sorted(missing))}")

    # 1. Generate sources.
    generated: list[Path] = []
    for shelf in shelves:
        src = render(shelf)
        path = GEN / f"{shelf['name']}.µcad"
        path.write_text(src, encoding="utf-8")
        generated.append(path)
        print(f"gen  {path.relative_to(ROOT)}")

    if args.gen_only:
        return 0

    # 2. Export each.
    mc = microcad()
    failures = 0
    for path in generated:
        cmd = [mc, "-C", str(CONFIG), "export"]
        if args.resolution:
            cmd += ["-r", args.resolution]
        cmd.append(str(path))
        print(f"export {path.name} ...", flush=True)
        res = subprocess.run(cmd, cwd=ROOT)
        if res.returncode != 0:
            failures += 1
            print(f"  FAILED: {path.name}", file=sys.stderr)

    if failures:
        print(f"\n{failures} shelf/shelves failed to export.", file=sys.stderr)
        return 1
    print(f"\nOK — {len(generated)} shelf/shelves exported to {BUILD.relative_to(ROOT)}/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
