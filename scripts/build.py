#!/usr/bin/env python3
"""Cluster-shelf pipeline: manifest -> generated µcad -> exported STL.

Reads shelves.toml and generates a single µcad root, `lib.mu`, next to the
`shelves.mu` library. Each manifest entry becomes one named, `#[export]`ed
statement in that root, and one `mucad export lib.mu` writes every STL into
build/.

Why one generated root in the repo root: µcad 0.6 resolves `mod shelves;`
relative to the source file (and a file named `lib.mu` resolves its modules
in its own directory), while the CLI no longer loads libraries from search
paths. So the root has to sit beside `shelves.mu`.

Usage:
    scripts/build.py                # generate + export everything
    scripts/build.py --gen-only     # only (re)generate lib.mu
    scripts/build.py tray_std ...   # build only the named shelves
"""
from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ROOT_SRC = ROOT / "lib.mu"
BUILD = ROOT / "build"
MANIFEST = ROOT / "shelves.toml"

VALID_DEVICES = {
    "rpi4", "rpi_zero", "pico", "nucleo", "nrf52840dk", "minipc",
}

# kind -> (workbench, needs_device)
VALID_KINDS = {
    "tray":        ("Tray",        False),
    "bolt_holder": ("BoltHolder",  True),
    "clip_holder": ("ClipHolder",  True),
    "cable_comb":  ("CableComb",   False),
    "cable_hook":  ("CableHook",   False),
}


HEADER = """// GENERATED by scripts/build.py from shelves.toml — do not edit by hand.
mod shelves;
"""


def render(shelf: dict) -> str:
    """Render one manifest entry to a named, exported µcad statement."""
    kind = shelf["kind"]
    name = shelf["name"]
    if not re.fullmatch(r"[a-z_][a-z0-9_]*", name):
        raise ValueError(f"{name!r}: shelf names must be lowercase identifiers")
    if kind not in VALID_KINDS:
        raise ValueError(f"{name}: unknown kind {kind!r}")
    workbench, needs_device = VALID_KINDS[kind]

    device = shelf.get("device")
    if needs_device and not device:
        raise ValueError(f"{name}: kind {kind!r} requires a `device`")
    if device and device not in VALID_DEVICES:
        raise ValueError(f"{name}: unknown device {device!r}")

    if kind == "tray":
        return _render_tray(name, kind, workbench, shelf, device)
    if kind in ("cable_comb", "cable_hook"):
        return _render_cable(name, kind, workbench, shelf)
    return _render_holder(name, kind, workbench, shelf, device)


def _render_cable(name, kind, workbench, shelf) -> str:
    """A cable-management accessory (comb or hook) that clips into a hex wall."""
    if kind == "cable_comb":
        teeth = shelf.get("teeth", 4)
        args = [f"teeth = {teeth}"]
    else:  # cable_hook
        opening = shelf.get("opening", "12mm")
        args = [f"opening = {opening}"]
    return _statement(name, kind, f"shelves::cables::{workbench}", args)


def _render_tray(name, kind, workbench, shelf, device) -> str:
    """A hex-grid tray. Device is optional (only sizes the height)."""
    # Trays are device-agnostic boxes; boards clip into the floor separately.
    if device:
        dev = f"shelves::devices::{device}"
        height = shelf.get("height", f"{dev}::TRAY_H")
        width = shelf.get("width", f"{dev}::FOOTPRINT_W")
        depth = shelf.get("depth", f"{dev}::FOOTPRINT_D")
    else:
        height = shelf.get("height", "26mm")
        width = shelf.get("width", "120mm")
        depth = shelf.get("depth", "90mm")

    args = [f"width = {width}", f"depth = {depth}", f"height = {height}"]
    return _statement(name, kind, f"shelves::tray::{workbench}", args, device)


def _render_holder(name, kind, workbench, shelf, device) -> str:
    """A press-in board holder (bolt or clip) for a specific device."""
    dev = f"shelves::devices::{device}"
    if kind == "bolt_holder":
        args = [
            f"board_w = {dev}::BOARD_W",
            f"board_d = {dev}::BOARD_D",
            f"hole_dx = {dev}::HOLE_DX",
            f"hole_dy = {dev}::HOLE_DY",
            f"post_d = {dev}::POST_D",
            f"screw_d = {dev}::SCREW_D",
            f"standoff_h = {dev}::STANDOFF_H",
        ]
    else:  # clip_holder
        args = [
            f"board_w = {dev}::BOARD_W",
            f"board_d = {dev}::BOARD_D",
            f"board_t = {dev}::BOARD_T",
        ]
    return _statement(name, kind, f"shelves::holders::{workbench}", args, device)


def _statement(name, kind, workbench, args, device=None) -> str:
    arg_block = ",\n    ".join(args)
    origin = f"kind={kind}" + (f", device={device}" if device else "")
    return f"""
// shelf: {name}  ({origin})
#[export("build/{name}.stl")]
{name} = {workbench}(
    {arg_block},
);
"""


def load_manifest() -> list[dict]:
    with MANIFEST.open("rb") as f:
        data = tomllib.load(f)
    shelves = data.get("shelf", [])
    if not shelves:
        sys.exit("shelves.toml contains no [[shelf]] entries")
    return shelves


def mucad() -> str:
    exe = shutil.which("mucad")
    if not exe:
        sys.exit("`mucad` not found on PATH. Install with: cargo install mucad@0.6.0")
    return exe


def main() -> int:
    ap = argparse.ArgumentParser(description="Build cluster shelves with µcad.")
    ap.add_argument("names", nargs="*", help="Only build these shelf names.")
    ap.add_argument("--gen-only", action="store_true", help="Generate sources, do not export.")
    ap.add_argument("--resolution", default=None, help="Export resolution, e.g. 0.05mm or 200%%.")
    args = ap.parse_args()

    BUILD.mkdir(exist_ok=True)

    shelves = load_manifest()
    if args.names:
        wanted = set(args.names)
        shelves = [s for s in shelves if s["name"] in wanted]
        missing = wanted - {s["name"] for s in shelves}
        if missing:
            sys.exit(f"unknown shelf name(s): {', '.join(sorted(missing))}")

    # 1. Generate the root source.
    src = HEADER + "".join(render(shelf) for shelf in shelves)
    ROOT_SRC.write_text(src, encoding="utf-8")
    print(f"gen  {ROOT_SRC.relative_to(ROOT)}  ({len(shelves)} shelf/shelves)")

    if args.gen_only:
        return 0

    # 2. Export every shelf in one go (each statement carries its #[export]).
    cmd = [mucad(), "export"]
    if args.resolution:
        cmd += ["-r", args.resolution]
    cmd.append(ROOT_SRC.name)
    res = subprocess.run(cmd, cwd=ROOT)
    if res.returncode != 0:
        print("\nexport failed.", file=sys.stderr)
        return 1
    print(f"\nOK — {len(shelves)} shelf/shelves exported to {BUILD.relative_to(ROOT)}/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
