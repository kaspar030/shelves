#!/usr/bin/env python3
"""Cluster-shelf pipeline: manifest -> generated µcad -> exported STL.

Reads shelves.toml, generates one .µcad source per entry into gen/, then
invokes `microcad export` for each, writing STLs into build/.

Usage:
    scripts/build.py                # generate + export everything
    scripts/build.py --gen-only     # only (re)generate gen/*.µcad
    scripts/build.py rpi4_tray ...  # build only the named shelves
"""
from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GEN = ROOT / "gen"
BUILD = ROOT / "build"
CONFIG = ROOT / ".microcad.toml"
MANIFEST = ROOT / "shelves.toml"

VALID_DEVICES = {
    "rpi4", "rpi_zero", "pico", "nucleo", "nrf52840dk", "minipc",
}

# kind -> (workbench, needs_device)
VALID_KINDS = {
    "tray":        ("Tray",        False),
    "drawer":      ("Drawer",      False),
    "bolt_holder": ("BoltHolder",  True),
    "clip_holder": ("ClipHolder",  True),
    "cable_comb":  ("CableComb",   False),
    "cable_hook":  ("CableHook",   False),
}


def render(shelf: dict) -> str:
    """Render one manifest entry to µcad source."""
    kind = shelf["kind"]
    name = shelf["name"]
    if kind not in VALID_KINDS:
        raise ValueError(f"{name}: unknown kind {kind!r}")
    workbench, needs_device = VALID_KINDS[kind]

    device = shelf.get("device")
    if needs_device and not device:
        raise ValueError(f"{name}: kind {kind!r} requires a `device`")
    if device and device not in VALID_DEVICES:
        raise ValueError(f"{name}: unknown device {device!r}")

    if kind in ("tray", "drawer"):
        return _render_tray(name, kind, workbench, shelf, device)
    if kind in ("cable_comb", "cable_hook"):
        return _render_cable(name, kind, workbench, shelf)
    return _render_holder(name, kind, workbench, shelf, device)


def _render_cable(name, kind, workbench, shelf) -> str:
    """A cable-management accessory (comb or hook) that clips into a hex wall."""
    if kind == "cable_comb":
        teeth = shelf.get("teeth", 4)
        args = [f"teeth = {teeth}"]
    else:  # cable_hook
        opening = shelf.get("opening", "12mm")
        args = [f"opening = {opening}"]
    arg_block = ",\n    ".join(args)
    return f"""// GENERATED by scripts/build.py from shelves.toml — do not edit by hand.
// shelf: {name}  (kind={kind})
use lib::cables::*;

#[export("build/{name}.stl")]
{workbench}(
    {arg_block},
);
"""


def _render_tray(name, kind, workbench, shelf, device) -> str:
    """A hex-grid tray/drawer. Device is optional (only sizes the height)."""
    # Trays are device-agnostic boxes; boards clip into the floor separately.
    if device:
        height = shelf.get("height", "dev::TRAY_H")
        width = shelf.get("width", "dev::FOOTPRINT_W")
        depth = shelf.get("depth", "dev::FOOTPRINT_D")
        use_dev = f"use lib::devices::{device} as dev;\n"
    else:
        height = shelf.get("height", "26mm")
        width = shelf.get("width", "120mm")
        depth = shelf.get("depth", "90mm")
        use_dev = ""

    args = [f"width = {width}", f"depth = {depth}", f"height = {height}"]
    arg_block = ",\n    ".join(args)
    return f"""// GENERATED by scripts/build.py from shelves.toml — do not edit by hand.
// shelf: {name}  (kind={kind}{', device=' + device if device else ''})
use lib::tray::*;
{use_dev}
#[export("build/{name}.stl")]
{workbench}(
    {arg_block},
);
"""


def _render_holder(name, kind, workbench, shelf, device) -> str:
    """A press-in board holder (bolt or clip) for a specific device."""
    if kind == "bolt_holder":
        args = [
            "board_w = dev::BOARD_W",
            "board_d = dev::BOARD_D",
            "hole_dx = dev::HOLE_DX",
            "hole_dy = dev::HOLE_DY",
            "post_d = dev::POST_D",
            "screw_d = dev::SCREW_D",
            "standoff_h = dev::STANDOFF_H",
        ]
    else:  # clip_holder
        args = [
            "board_w = dev::BOARD_W",
            "board_d = dev::BOARD_D",
            "board_t = dev::BOARD_T",
        ]
    arg_block = ",\n    ".join(args)
    return f"""// GENERATED by scripts/build.py from shelves.toml — do not edit by hand.
// shelf: {name}  (kind={kind}, device={device})
use lib::holders::*;
use lib::devices::{device} as dev;

#[export("build/{name}.stl")]
{workbench}(
    {arg_block},
);
"""


def load_manifest() -> list[dict]:
    with MANIFEST.open("rb") as f:
        data = tomllib.load(f)
    shelves = data.get("shelf", [])
    if not shelves:
        sys.exit("shelves.toml contains no [[shelf]] entries")
    return shelves


def microcad() -> str:
    exe = shutil.which("microcad")
    if not exe:
        sys.exit("`microcad` not found on PATH. Install with: cargo install microcad")
    return exe


def main() -> int:
    ap = argparse.ArgumentParser(description="Build cluster shelves with microcad.")
    ap.add_argument("names", nargs="*", help="Only build these shelf names.")
    ap.add_argument("--gen-only", action="store_true", help="Generate sources, do not export.")
    ap.add_argument("--resolution", default=None, help="Export resolution, e.g. 0.05mm or 200%%.")
    args = ap.parse_args()

    GEN.mkdir(exist_ok=True)
    BUILD.mkdir(exist_ok=True)

    shelves = load_manifest()
    if args.names:
        wanted = set(args.names)
        shelves = [s for s in shelves if s["name"] in wanted]
        missing = wanted - {s["name"] for s in shelves}
        if missing:
            sys.exit(f"unknown shelf name(s): {', '.join(sorted(missing))}")

    # 1. Generate sources.
    generated: list[Path] = []
    for shelf in shelves:
        src = render(shelf)
        path = GEN / f"{shelf['name']}.µcad"
        path.write_text(src, encoding="utf-8")
        generated.append(path)
        print(f"gen  {path.relative_to(ROOT)}")

    if args.gen_only:
        return 0

    # 2. Export each.
    mc = microcad()
    failures = 0
    for path in generated:
        cmd = [mc, "-C", str(CONFIG), "export"]
        if args.resolution:
            cmd += ["-r", args.resolution]
        cmd.append(str(path))
        print(f"export {path.name} ...", flush=True)
        res = subprocess.run(cmd, cwd=ROOT)
        if res.returncode != 0:
            failures += 1
            print(f"  FAILED: {path.name}", file=sys.stderr)

    if failures:
        print(f"\n{failures} shelf/shelves failed to export.", file=sys.stderr)
        return 1
    print(f"\nOK — {len(generated)} shelf/shelves exported to {BUILD.relative_to(ROOT)}/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
